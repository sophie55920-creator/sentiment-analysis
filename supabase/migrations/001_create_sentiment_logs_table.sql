-- ==============================================================================
-- 001_create_sentiment_logs_table.sql
-- 설명: 감성 분석 결과를 저장하기 위한 sentiment_logs 테이블 및 인덱스 생성 스크립트
-- ==============================================================================

-- 1. sentiment_logs 테이블 생성
-- 사용자가 입력한 텍스트, 감성 판별 결과, 신뢰도(0~100), 한국어 이유, 생성 일시를 저장합니다.
create table if not exists sentiment_logs (
    id bigint generated by default as identity primary key,
    input_text text not null,
    sentiment text not null check (sentiment in ('positive', 'negative', 'neutral')),
    confidence integer not null check (confidence >= 0 and confidence <= 100),
    reason text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. 최신 순 조회 성능을 위한 인덱스 생성
create index if not exists idx_sentiment_logs_created_at on sentiment_logs (created_at desc);

-- 3. Row Level Security (RLS) 활성화
-- 클라이언트 브라우저에서의 직접적인 무단 조작을 방지하고 백엔드 서버(service_role 키)를 통해서만 안전하게 쓰기를 허용합니다.
alter table sentiment_logs enable row level security;

